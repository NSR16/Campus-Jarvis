CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    source TEXT NOT NULL,
    document_type TEXT NOT NULL,
    content_sha256 TEXT NOT NULL
        CONSTRAINT ck_documents_content_sha256
        CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_documents_content_sha256 UNIQUE (content_sha256)
);

ALTER TABLE documents
    ADD COLUMN IF NOT EXISTS content_sha256 TEXT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_documents_content_sha256'
          AND conrelid = 'public.documents'::regclass
    ) THEN
        ALTER TABLE documents
            ADD CONSTRAINT ck_documents_content_sha256
            CHECK (content_sha256 ~ '^[0-9a-f]{64}$');
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_documents_content_sha256
    ON documents (content_sha256);

CREATE TABLE IF NOT EXISTS document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL,
    embedding VECTOR(768) NOT NULL,
    CONSTRAINT uq_document_chunks_document_id_chunk_index
        UNIQUE (document_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS idx_documents_source
    ON documents (source);

CREATE INDEX IF NOT EXISTS idx_documents_document_type
    ON documents (document_type);

CREATE INDEX IF NOT EXISTS idx_documents_created_at
    ON documents (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_document_chunks_embedding_hnsw
    ON document_chunks USING hnsw (embedding vector_cosine_ops);